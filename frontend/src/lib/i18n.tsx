interface CtxValor { idioma: Idioma; setIdioma: (i: Idioma) => void; t: (chave: string, vars?: Record<string, string | number>) => string }
const IdiomaCtx = createContext<CtxValor | null>(null)

export function ehIdiomaValido(v: unknown): v is Idioma {
  return v === 'pt' || v === 'en' || v === 'en-gb' || v === 'es'
}

/** Prioriza o idioma salvo no perfil do usuário logado (persistido no banco); sem sessão,
 *  cai para a escolha anônima salva no localStorage (ex.: visitante da landing). */
function idiomaSalvo(): Idioma {
  const usuarioRaw = localStorage.getItem('modacrm_usuario')
  if (usuarioRaw) {
    try {
      const idiomaUsuario = JSON.parse(usuarioRaw)?.idioma
      if (ehIdiomaValido(idiomaUsuario)) return idiomaUsuario
    } catch { /* ignora JSON inválido */ }
  }
  const salvo = localStorage.getItem(CHAVE)
  return ehIdiomaValido(salvo) ? salvo : 'pt'
}

export function IdiomaProvider({ children }: { children: ReactNode }) {
  const [idioma, setIdiomaState] = useState<Idioma>(idiomaSalvo)

  function setIdioma(i: Idioma) {
    localStorage.setItem(CHAVE, i)
    setIdiomaState(i)
  }

  function t(chave: string, vars?: Record<string, string | number>): string {
    let valor = DICIONARIOS[idioma][chave]
    // en-gb é um dicionário ENXUTO (só as diferenças do en-US) — cai pro 'en' antes do pt.
    if (!valor && idioma === 'en-gb') valor = DICIONARIOS.en[chave]
    if (!valor) valor = DICIONARIOS.pt[chave] ?? chave
    if (vars) for (const [k, v] of Object.entries(vars)) valor = valor.replace(`{${k}}`, String(v))
    return valor
  }

  return <IdiomaCtx.Provider value={{ idioma, setIdioma, t }}>{children}</IdiomaCtx.Provider>
}

export function useIdioma(): CtxValor {
  const ctx = useContext(IdiomaCtx)
  if (!ctx) throw new Error('useIdioma precisa estar dentro de <IdiomaProvider>')
  return ctx
}
